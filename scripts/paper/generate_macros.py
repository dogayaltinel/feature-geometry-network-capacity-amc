"""Generate result macros without inventing scientific values.

The default mode writes explicit ``TBD`` placeholders. A locked summary JSON
may be supplied later; unknown keys are rejected so a typo cannot silently
produce an incomplete manuscript.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


DEFAULT_KEYS = (
    "n_runs",
    "n_seeds",
    "n_splits",
    "epoch_budget",
    "feature_effect",
    "capacity_effect",
    "interaction_effect",
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--placeholder", action="store_true")
    args = parser.parse_args()

    values = {key: "TBD" for key in DEFAULT_KEYS}
    if args.summary:
        payload = json.loads(args.summary.read_text(encoding="utf-8"))
        unknown = sorted(set(payload) - set(DEFAULT_KEYS))
        if unknown:
            raise SystemExit(f"Unknown summary keys: {', '.join(unknown)}")
        values.update({key: str(value) for key, value in payload.items()})
    elif not args.placeholder:
        raise SystemExit("Use --summary with locked results or --placeholder before results exist")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by feature_geometry_study/scripts/paper/generate_macros.py", "% Do not hand-edit result values."]
    for key, value in values.items():
        macro = "\\fg" + "".join(part.capitalize() for part in key.split("_"))
        lines.append(f"\\newcommand{{{macro}}}{{{value}}}")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
